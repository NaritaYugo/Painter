#pragma once

#include <QString>

// ---------------------------------------------------------------------------
// ウィンドウまわりの挙動を追うための診断ログ
// ---------------------------------------------------------------------------
// フレームレスウィンドウ(タイトルバー非表示)にしてから、
//   ・起動時に数回点滅する
//   ・メニューを開閉するだけで点滅する
//   ・メニューバーが透明になる
//   ・キャンバスを開くときに暗転する
// といった描画の乱れが出ている。対症療法で潰そうとしても当たらなかったため、
// 「いつ・誰が・何をきっかけに全面再描画を起こしているか」を実測できるようにする。
//
// 環境変数 TIEPOLO_WINLOG で有効化する(未設定なら完全に無効でコストもゼロ)。
//   TIEPOLO_WINLOG=1 ... メインウィンドウ宛のメッセージと自前処理の呼び出しを記録
//   TIEPOLO_WINLOG=2 ... マウス移動・ヒットテストなど高頻度なものも含めて全部
//   TIEPOLO_WINLOG=3 ... メニューのポップアップなど他のウィンドウ宛も含めて全部
//                        (メニュー開閉時のちらつきはメインウィンドウ宛のメッセージ
//                         には現れないため、ポップアップ側を見るにはこれが要る)
//
// 出力先は既定で %TEMP%\tiepolo-winlog.txt。Release版はコンソールを持たない
// (WIN32サブシステム)ため、標準エラー出力ではなくファイルに落とす必要がある。
// TIEPOLO_WINLOG_FILE で出力先を変えられる。
//
// 1行ずつ書いて即フラッシュする。点滅の再現後にプロセスを強制終了しても
// 直前までのログが残るようにするため(バッファに溜めると肝心の末尾が消える)。
// ---------------------------------------------------------------------------
namespace WinLog {

int  level();            // TIEPOLO_WINLOG の値(未設定なら0)
bool enabled();          // TIEPOLO_WINLOG >= 1
bool verbose();          // TIEPOLO_WINLOG >= 2
void write(const QString &line);
QString path();          // 実際の出力先(起動時に1行目へ出す)

} // namespace WinLog

// enabled()が偽なら引数の文字列を組み立てすらしないようにマクロで包む
// (QString連結は安くないので、無効時にコストを残さない)。
#define WINLOG(expr)   do { if (WinLog::enabled()) WinLog::write(expr); } while (false)
#define WINLOG_V(expr) do { if (WinLog::verbose()) WinLog::write(expr); } while (false)
