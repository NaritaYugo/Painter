#pragma once

#include "io/AbrCodec.h"
#include "tools/core/ToolConfig.h"

#include <QStringList>

// ===========================================================================
// AbrPenMapping  ―  .abr のブラシ設定 と PenToolConfig の対応付け
// ---------------------------------------------------------------------------
// 対応するのは「両方に同じ意味の設定がある」ものだけ:
//     先端画像 / サイズ / 硬さ / スタンプ間隔 / 角度 / 真円率 / 最小サイズ /
//     サイズのランダム / 角度のランダム / 不透明度のランダム /
//     散布量 / 粒子数 / 進行方向に追従
//
// 片方にしか無いものは移せない。移せなかったものは notes に入れて呼び出し側が
// 利用者へ提示する(黙って落とさない)。
//   Photoshop側のみ: デュアルブラシ / ウェットエッジ / ノイズ / カラー動的 /
//                    テクスチャ(パターン) / ビルドアップ など
//   このアプリ側のみ: フロー / 合成モード / 筆圧カーブ / 傾き /
//                    紙質 / 入り抜き / 後補正 / 混色 / 色のランダム など
// ===========================================================================
namespace AbrPenMapping {

// .abr のブラシ1本を、ペンの設定へ反映する。
// 入っていなかった項目は今の値のまま(上書きしない)。
// 先端画像が入っていた場合はPNGとしてアプリのデータフォルダへ保存し、
// そのパスをペンの先端画像に設定する。
QStringList applyToPen(const AbrBrush &brush, PenToolConfig &pen);

// 今のペンの設定を .abr のブラシ1本として書き出せる形にする。
// 先端画像が既定の丸以外なら、その画像も一緒に持たせる。
AbrBrush fromPen(const PenToolConfig &pen, const QString &name);

// 今のペンの設定のうち、.abr へ移せないもの(=書き出しても失われるもの)の一覧。
// 既定値のままの項目は「使っていない」ので挙げない。
QStringList unmappedFromPen(const PenToolConfig &pen);

} // namespace AbrPenMapping
