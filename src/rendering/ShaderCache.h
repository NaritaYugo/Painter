#pragma once

#include <QString>
#include <QStringList>

#include <functional>

class QOpenGLShaderProgram;

// ===========================================================================
// ShaderCache  ―  シェーダープログラムのプロセス全体キャッシュ + 事前コンパイル
// ---------------------------------------------------------------------------
// 【なぜ1箇所に集めるのか】
// main.cpp で Qt::AA_ShareOpenGLContexts を有効にしているため、すべての
// QOpenGLWidget のコンテキストは同一の共有グループに属する。共有グループ内では
// プログラムオブジェクトをそのまま使い回せるので、タブごとにコンパイルする必要が
// 無い。以前はタブ1枚につき30本以上を丸ごとコンパイルし直しており、実測で
// 1枚あたり約2.8秒かかっていた。
//
// 所有権はこのキャッシュが持つ。呼び出し側は絶対に delete しないこと
// (1つのタブを閉じただけで他のタブが使っているプログラムまで壊れる)。
// プロセス終了まで生かしておき、GL資源は共有グループの破棄時に解放される。
//
// 【なぜ裏で先に作るのか】
// OpenGLのGLSLはドライバが実行時にコンパイルする。可搬な事前コンパイル形式が
// 無いので、どうやってもどこかで1回はコンパイルが要る(実測でこの環境の初回は
// 合計約5.5秒。内訳は render.vert+frag が約3.0秒、belowComposite.comp が約1.0秒)。
// これが「最初のキャンバスを開いた瞬間」にまとめて乗ると、その間UIスレッドが
// 止まってウィンドウが固まる。
//
// そこで起動直後に、共有グループへ参加した専用コンテキストをワーカースレッドで
// 作り、そちらで全部コンパイルしておく。利用者がスタートページを見ている間に
// 終わるので、キャンバスを開くときには出来上がったものを引くだけになる。
//
// 間に合わなかった場合(起動直後にすぐキャンバスを開いた場合)も壊れない:
// 同じシェーダーを2スレッドが同時に作りに行かないよう、作成中のものは
// 「待つ」ようにしてある(二重にコンパイルしてGPUを二重に使うのを防ぐ)。
// ===========================================================================
namespace ShaderCache {

// コンピュートシェーダー1本。無ければその場でコンパイルする。
// 呼び出し側のスレッドでGLコンテキストがカレントになっていること。
QOpenGLShaderProgram *compute(const QString &path);

// 画面描画用(render.vert + render.frag)。
QOpenGLShaderProgram *render();

// キャンバスを開いて描き始めるのに要るシェーダー。これが揃った時点で操作を
// 解禁してよい(setReadyForUseCallback)。
QStringList essentialWarmUp();

// 事前コンパイルの対象。essentialWarmUp() の後ろに、使うまで要らないもの
// (フィルタ・変形・色調補正など)を並べたもの。
// シェーダーを追加したらここにも足すこと。足し忘れても「事前に作られない」だけで
// 動作は変わらない。
QStringList warmUpOrder();

// 起動直後に一度だけメインスレッドから呼ぶ。ワーカースレッドで warmUpOrder() を
// 順に作る。GLコンテキストがまだ無い環境では何もしない。
// 終了時に止めるため、QCoreApplication::aboutToQuit への接続もここで行う。
void startBackgroundWarmUp();

// essentialWarmUp() が揃った時点でメインスレッドから呼ばれる(残りは裏で継続)。
// startBackgroundWarmUp() より前に設定すること。事前コンパイルを行わない場合
// (共有コンテキストが無い/環境変数で無効にした場合)も、その場で必ず一度呼ばれる。
//
// 用途: ここまでは起動画面を出したまま入力を止めておく(main.cpp)。
// 事前コンパイル中はドライバがGPUを占有するため、UIスレッドは動いていても
// 画面への反映が大きく遅れる(実測: 重い4本を作っている間、クリックが画面に
// 出るまで3.9秒。残りは1本あたり最大133msなので操作の邪魔にならない)。
void setReadyForUseCallback(std::function<void()> cb);

// 事前コンパイルを打ち切り、ワーカースレッドの終了を待つ。
//
// 終了処理でQtが共有コンテキストを壊すより前に必ず呼ぶこと。裏でコンパイル中の
// まま壊されるとアクセス違反で落ちる(実測: 事前コンパイル中にAlt+F4すると
// 終了コード 0xC0000005)。startBackgroundWarmUp() が aboutToQuit へ繋ぐので、
// 通常は呼び出し側が意識する必要は無い。
//
// コンパイル中の1本は途中で止められない(ドライバの処理なので)ため、
// 最大でその1本ぶんだけ待つ。
void stopBackgroundWarmUp();

} // namespace ShaderCache
